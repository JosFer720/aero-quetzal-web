import { test, expect } from "@playwright/test";

test("cliente reserva en PostgreSQL, empleado hace Check-In y el público ve el estado final", async ({ page, browser }) => {
  await page.goto("/");
  await page.getByLabel("Origen", { exact: true }).selectOption("GUA");
  await page.getByLabel("Destino", { exact: true }).selectOption("SAL");
  await page.getByLabel("Fecha de salida").fill("2099-11-05");
  await page.getByRole("button", { name: "Buscar vuelos", exact: true }).click();
  await page.getByRole("button", { name: "Elegir vuelo" }).click();
  await page.getByLabel("Nombres", { exact: true }).fill("Ana");
  await page.getByLabel("Apellidos", { exact: true }).fill("López");
  await page.getByLabel("Número de documento", { exact: true }).fill("P1234567");
  await page.getByLabel("Correo de contacto").fill("ana@example.com");
  await page.getByRole("button", { name: "Confirmar reserva gratuita" }).click();
  await expect(page.getByRole("heading", { name: "Reserva gratuita confirmada" })).toBeVisible();
  const code = (await page.locator("body").innerText()).match(/\bAQ[A-Z0-9]{5}\b/)?.[0];
  expect(code).toBeTruthy();
  const staffContext = await browser.newContext();
  const staff = await staffContext.newPage();
  await staff.goto("http://127.0.0.1:5174/check-in");
  await staff.getByLabel("Usuario", { exact: true }).fill("checkin");
  await staff.getByLabel("Contraseña").fill("integrated-test-only");
  await staff.getByRole("button", { name: "Entrar a operaciones" }).click();
  await staff.getByLabel("Código de reserva").fill(code!);
  await staff.getByRole("button", { name: "Consultar reserva" }).click();
  await staff.getByRole("button", { name: "Confirmar Check-In y asignar asientos" }).click();
  await expect(staff.getByRole("cell", { name: "1A", exact: true })).toBeVisible();
  await staff.reload();
  await staff.getByLabel("Código de reserva").fill(code!);
  await staff.getByRole("button", { name: "Consultar reserva" }).click();
  await expect(staff.getByText("Esta reserva ya tiene Check-In.", { exact: false })).toBeVisible();
  expect((await staff.request.get("http://127.0.0.1:5174/api/v1/internal/flights")).status()).toBe(403);
  await page.reload();
  await page.getByLabel("Código de reserva").fill(code!);
  await page.getByLabel("Documento de verificación").fill("P1234567");
  await page.getByRole("button", { name: "Consultar reserva", exact: true }).click();
  await expect(page.getByLabel("Resumen de reserva")).toContainText("Check-In completado");
  await expect(page.getByRole("button", { name: "Cancelar reserva", exact: true })).toHaveCount(0);
  await staff.getByRole("button", { name: "Cerrar sesión" }).click();
  expect((await staff.request.get("http://127.0.0.1:5174/api/v1/internal/reservations?q=Ana")).status()).toBe(401);
  await staffContext.close();
});
